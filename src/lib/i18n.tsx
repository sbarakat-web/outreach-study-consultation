const LOCALES: Record<Lang, string> = { en: "en-GB", fr: "fr-FR", es: "es-ES", ar: "ar-u-nu-latn" };

let current: Lang = "en";

/** Locale for Intl date formatting (read by formatSlot and the calendar). */
export const currentLocale = () => LOCALES[current];

function detect(): Lang {
  const isLang = (v: string | null | undefined): v is Lang => !!v && v in DICTS;
  const fromUrl = new URLSearchParams(window.location.search).get("lang");
  if (isLang(fromUrl)) return fromUrl;
  try {
    const saved = localStorage.getItem("lang");
    if (isLang(saved)) return saved;
  } catch {
    // storage unavailable
  }
  const browser = (navigator.language || "en").slice(0, 2);
  return isLang(browser) ? browser : "en";
}

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  /** Translate a stored English value (programme, status label, document type…). */
  tv: (value: string | null | undefined) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (current = detect()));

  useEffect(() => {
    current = lang;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    try {
      localStorage.setItem("lang", lang);
    } catch {
      // storage unavailable
    }
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    current = l;
    setLangState(l);
  }, []);

  const t = useCallback(
    (key: Key, vars?: Record<string, string | number>) => {
      let s = DICTS[lang][key] ?? en[key];
      for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  const tv = useCallback((value: string | null | undefined) => (value ? (lang === "en" ? value : VALUES[lang][value] ?? value) : ""), [lang]);

  return <I18nContext.Provider value={{ lang, setLang, t, tv }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
