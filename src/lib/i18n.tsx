export type Key = keyof typeof en;

/** Locale for Intl date formatting (read by formatSlot and the calendar). */
export const currentLocale = () => "en-GB";

interface I18n {
  lang: Lang;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  /** Display a stored value (programme, status label, document type…). */
  tv: (value: string | null | undefined) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = "en";
    document.documentElement.dir = "ltr";
  }, []);

  const t = useCallback((key: Key, vars?: Record<string, string | number>) => {
    let s: string = en[key];
    for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  }, []);

  const tv = useCallback((value: string | null | undefined) => value ?? "", []);

  return <I18nContext.Provider value={{ lang: "en", t, tv }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
